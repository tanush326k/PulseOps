# ---------------------------------------------------------------------------
# 4. Bedrock provider — runtime error (quota, network, auth)
# ---------------------------------------------------------------------------


class TestBedrockRuntimeError(unittest.TestCase):

    def _mock_strands_module(self, side_effect):
        """Return a fake strands module whose Agent(...)(msg) raises side_effect."""
        mock_agent_instance = MagicMock()
        mock_agent_instance.side_effect = side_effect
        mock_agent_class = MagicMock(return_value=mock_agent_instance)
        mock_strands = MagicMock()
        mock_strands.Agent = mock_agent_class
        return mock_strands

    def test_throttling_returns_unavailable(self):
        fake_strands = self._mock_strands_module(
            Exception("ThrottlingException: Rate exceeded")
        )
        with patch.dict(os.environ, {"ASSESSMENT_PROVIDER": "bedrock"}), \
             patch.dict("sys.modules", {"strands": fake_strands}):
            r = ba.assess_incident(BASE_INCIDENT, _ACTION, _EVIDENCE)
        self.assertEqual(r["status"], "unavailable")
        self.assertFalse(r["available"])

    def test_auth_error_returns_unavailable(self):
        fake_strands = self._mock_strands_module(
            Exception("AccessDeniedException: not authorized")
        )
        with patch.dict(os.environ, {"ASSESSMENT_PROVIDER": "bedrock"}), \
             patch.dict("sys.modules", {"strands": fake_strands}):
            r = ba.assess_incident(BASE_INCIDENT, _ACTION, _EVIDENCE)
        self.assertEqual(r["status"], "unavailable")
        self.assertIn("AccessDeniedException", r["assessment"])

    def test_runtime_error_provider_stays_bedrock(self):
        fake_strands = self._mock_strands_module(RuntimeError("network timeout"))
        with patch.dict(os.environ, {"ASSESSMENT_PROVIDER": "bedrock"}), \
             patch.dict("sys.modules", {"strands": fake_strands}):
            r = ba.assess_incident(BASE_INCIDENT, _ACTION, _EVIDENCE)
        self.assertEqual(r["provider"], "bedrock")


