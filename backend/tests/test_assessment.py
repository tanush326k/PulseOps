"""Tests for bedrock_agent.py — assessment providers.

Tests all four code paths in assess_incident():
  1. Mock provider  (ASSESSMENT_PROVIDER=mock, no external services)
  2. Bedrock live   (ASSESSMENT_PROVIDER=bedrock, strands.Agent mocked)
  3. Bedrock import error (strands-agents not installed)
  4. Bedrock runtime error (API call fails, e.g. throttling)
  5. Invalid/unknown provider value
  6. Provider defaults to mock when env var is unset

No live AWS calls, no model downloads, no credentials required.

Run:
    cd backend
    ~/strands-decider/.venv/bin/python -m pytest tests/test_assessment.py -v
"""
from __future__ import annotations

import os
import sys
import unittest
from unittest.mock import MagicMock, patch

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import pulseops.bedrock_agent as ba


# ---------------------------------------------------------------------------
# Shared fixtures
# ---------------------------------------------------------------------------

BASE_INCIDENT = {
    "id": "INC-T001",
    "severity": "P1",
    "service": "payments-gateway",
    "title": "Error rate spike",
    "description": "5xx spike after deploy",
}

_ACTION    = "compare_deployments"
_EVIDENCE  = "[SIMULATED] Deployment diff shows PAYMENT_URL changed."


def _assess(provider: str, incident=None, action=None, evidence=None) -> dict:
    """Call assess_incident with the given ASSESSMENT_PROVIDER env var."""
    inc  = incident or BASE_INCIDENT
    act  = action   or _ACTION
    evid = evidence or _EVIDENCE
    with patch.dict(os.environ, {"ASSESSMENT_PROVIDER": provider}):
        return ba.assess_incident(inc, act, evid)


# ---------------------------------------------------------------------------
# 1. Mock provider
# ---------------------------------------------------------------------------


class TestMockProvider(unittest.TestCase):

    def test_mock_status_field(self):
        r = _assess("mock")
        self.assertEqual(r["status"], "mock")

    def test_mock_provider_field(self):
        r = _assess("mock")
        self.assertEqual(r["provider"], "mock")

    def test_mock_available_is_false(self):
        """Mock assessment correctly reports available=False (not live Bedrock)."""
        r = _assess("mock")
        self.assertFalse(r["available"])

    def test_mock_model_is_none(self):
        r = _assess("mock")
        self.assertIsNone(r["model"])

    def test_mock_label_present(self):
        r = _assess("mock")
        self.assertIn("MOCK", r["label"])
        self.assertNotIn("BEDROCK", r["label"].upper().replace("NOT GENERATED BY BEDROCK", ""))

    def test_mock_assessment_text_contains_situation(self):
        r = _assess("mock")
        self.assertIn("SITUATION", r["assessment"])

    def test_mock_assessment_text_contains_evidence(self):
        r = _assess("mock")
        self.assertIn("EVIDENCE", r["assessment"])

    def test_mock_assessment_text_contains_next_steps(self):
        r = _assess("mock")
        self.assertIn("NEXT STEPS", r["assessment"])

    def test_mock_assessment_mentions_action(self):
        r = _assess("mock")
        self.assertIn(_ACTION, r["assessment"])

    def test_mock_assessment_mentions_service(self):
        r = _assess("mock")
        self.assertIn(BASE_INCIDENT["service"], r["assessment"])

    def test_mock_is_deterministic(self):
        """Two calls with the same input produce the same assessment text."""
        r1 = _assess("mock")
        r2 = _assess("mock")
        self.assertEqual(r1["assessment"], r2["assessment"])

    def test_mock_text_explicitly_says_not_bedrock(self):
        r = _assess("mock")
        text = r["assessment"].upper()
        self.assertIn("MOCK", text)


