# ---------------------------------------------------------------------------
# 7. Response contract — all responses have required keys
# ---------------------------------------------------------------------------


class TestResponseContract(unittest.TestCase):
    """Every code path must return dicts with the same set of top-level keys."""

    REQUIRED_KEYS = {"assessment", "model", "available", "provider", "status", "label"}

    def _check(self, result):
        missing = self.REQUIRED_KEYS - result.keys()
        self.assertFalse(missing, f"Keys missing from response: {missing}")

    def test_mock_has_all_keys(self):
        self._check(_assess("mock"))

    def test_invalid_provider_has_all_keys(self):
        self._check(_assess("garbage_value"))

    def test_bedrock_import_error_has_all_keys(self):
        with patch.dict(os.environ, {"ASSESSMENT_PROVIDER": "bedrock"}), \
             patch.dict("sys.modules", {"strands": None}):
            r = ba.assess_incident(BASE_INCIDENT, _ACTION, _EVIDENCE)
        self._check(r)

    def test_bedrock_runtime_error_has_all_keys(self):
        fake = MagicMock()
        fake.Agent = MagicMock(return_value=MagicMock(side_effect=RuntimeError("boom")))
        with patch.dict(os.environ, {"ASSESSMENT_PROVIDER": "bedrock"}), \
             patch.dict("sys.modules", {"strands": fake}):
            r = ba.assess_incident(BASE_INCIDENT, _ACTION, _EVIDENCE)
        self._check(r)


