"""Incident assessment providers for PulseOps.

Mock mode is self-contained and is the default. Bedrock mode is opt-in via
ASSESSMENT_PROVIDER=bedrock. Diagnostic evidence is simulated in this demo.
"""
from __future__ import annotations

import os
from typing import Any

BEDROCK_MODEL_ID = os.environ.get(
    "BEDROCK_MODEL_ID", "us.amazon.nova-lite-v1:0"
)

ASSESSMENT_PROMPT = """\
You are an expert SRE (Site Reliability Engineer) acting as an incident
commander. Assess the incident and supplied diagnostic evidence.
Distinguish observed facts from hypotheses. Do not claim a root cause is
confirmed unless the evidence establishes it. Include SITUATION, EVIDENCE,
and NEXT STEPS. Keep the response under 300 words.
The diagnostic evidence is simulated for demonstration purposes.
"""


def _mock_assessment(
    incident: dict[str, Any],
    action_taken: str,
    evidence: str,
) -> dict[str, Any]:
    """Build a deterministic assessment without external services."""
    title = incident.get("title", "Unspecified incident")
    service = incident.get("service", "unknown service")
    severity = incident.get("severity", "unknown")
    description = incident.get("description", "No description provided.")

    assessment = (
        "MOCK ASSESSMENT — NOT GENERATED BY BEDROCK\n\n"
        "SITUATION\n"
        f"{severity} incident affecting {service}: {title}. "
        f"Reported details: {description} "
        "This is a demo assessment, not a verified diagnosis.\n\n"
        "EVIDENCE\n"
        f"- Diagnostic action selected by Strands Decider: {action_taken}\n"
        "- Evidence below is simulated and has not been checked against "
        "live infrastructure.\n"
        f"{evidence}\n\n"
        "NEXT STEPS\n"
        "1. Validate these findings against live logs, metrics, and "
        "deployment records.\n"
        "2. Confirm the suspected cause before making production changes.\n"
        "3. Follow your incident-response and rollback procedures as "
        "appropriate."
    )

    return {
        "assessment": assessment,
        "model": None,
        "available": False,
        "provider": "mock",
        "status": "mock",
        "label": "MOCK — NOT GENERATED BY BEDROCK",
    }


def _unavailable_response(reason: str) -> dict[str, Any]:
    """Describe a failed Bedrock assessment without disguising it as a mock."""
    return {
        "assessment": (
            f"Bedrock assessment unavailable: {reason}\n\n"
            "No live model assessment was generated. Switch to "
            "ASSESSMENT_PROVIDER=mock for a self-contained demo, or check "
            "the Bedrock configuration before retrying."
        ),
        "model": BEDROCK_MODEL_ID,
        "available": False,
        "provider": "bedrock",
        "status": "unavailable",
        "label": "BEDROCK UNAVAILABLE",
    }


def _bedrock_assessment(
    incident: dict[str, Any],
    action_taken: str,
    evidence: str,
) -> dict[str, Any]:
    """Call the existing Strands Agents SDK integration with Bedrock."""
    try:
        from strands import Agent
    except ImportError:
        return _unavailable_response("strands-agents is not installed")

    user_msg = (
        f"INCIDENT DETAILS\n"
        f"ID: {incident.get('id', 'N/A')}\n"
        f"Severity: {incident.get('severity', 'unknown')}\n"
        f"Service: {incident.get('service', 'unknown')}\n"
        f"Title: {incident.get('title', '')}\n"
        f"Description: {incident.get('description', '')}\n\n"
        f"DIAGNOSTIC ACTION: {action_taken}\n\n"
        f"SIMULATED EVIDENCE\n{evidence}\n\n"
        "Produce the incident assessment."
    )

    try:
        agent = Agent(
            model=BEDROCK_MODEL_ID,
            system_prompt=ASSESSMENT_PROMPT,
        )
        result = agent(user_msg)
        return {
            "assessment": str(result),
            "model": BEDROCK_MODEL_ID,
            "available": True,
            "provider": "bedrock",
            "status": "live",
            "label": f"BEDROCK — {BEDROCK_MODEL_ID}",
        }
    except Exception as exc:
        return _unavailable_response(f"{type(exc).__name__}: {exc}")


def assess_incident(
    incident: dict[str, Any],
    action_taken: str,
    evidence: str,
) -> dict[str, Any]:
    """Assess an incident using the explicitly configured provider.

    ASSESSMENT_PROVIDER defaults to ``mock``. Set it to ``bedrock`` to opt
    into the live Strands Agents / Amazon Bedrock integration.
    """
    provider = os.environ.get("ASSESSMENT_PROVIDER", "mock").strip().lower()

    if provider == "mock":
        return _mock_assessment(incident, action_taken, evidence)

    if provider == "bedrock":
        return _bedrock_assessment(incident, action_taken, evidence)

    return {
        **_unavailable_response(
            f"unknown ASSESSMENT_PROVIDER value: {provider!r}"
        ),
        "status": "configuration_error",
        "label": "ASSESSMENT CONFIGURATION ERROR",
    }
