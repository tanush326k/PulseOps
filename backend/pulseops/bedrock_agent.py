"""Incident assessment providers for PulseOps.

Mock mode is self-contained and is the default. Bedrock mode is opt-in via
ASSESSMENT_PROVIDER=bedrock. Diagnostic evidence is simulated in this demo.
"""
from __future__ import annotations

import os
import re
from typing import Any

BEDROCK_MODEL_ID = os.environ.get(
    "BEDROCK_MODEL_ID", "us.amazon.nova-lite-v1:0"
)

ASSESSMENT_PROMPT = """\
You are an expert SRE (Site Reliability Engineer) acting as an incident
commander. Assess the incident and supplied diagnostic evidence.
Distinguish observed facts from hypotheses. Do not claim a root cause is
confirmed unless the evidence establishes it. Include SITUATION, EVIDENCE,
and NEXT STEPS. Keep the response under 300 words.
The diagnostic evidence is simulated for demonstration purposes.
"""


def _sanitize_error_message(msg: str) -> str:
    """Strip credential patterns from error messages to prevent credential leakage."""
    msg = re.sub(
        r'(?i)(aws_secret_access_key|secret_key|password|token)\s*[:=]\s*\S+',
        r'\1=***',
        msg,
    )
    msg = re.sub(r'\b(AKIA[0-9A-Z]{16})\b', r'AKIA***', msg)
    return msg


def classify_bedrock_error(exc: Exception) -> tuple[str, str, str]:
    """Classify an exception into (category, descriptive_message, badge_label).

    Categories:
      - missing_credentials: AWS credentials unset, missing, or incomplete
      - access_denied: IAM or model invocation permissions insufficient
      - throttling: token-per-day, rate limit, or service quota exceeded (fail fast)
      - timeout: network connect/read timeout
      - import_error: SDK / dependency missing
      - service_error: other Bedrock API / service errors
    """
    exc_type = type(exc).__name__
    exc_msg = str(exc)
    exc_lower = f"{exc_type} {exc_msg}".lower()

    # 1. Missing credentials
    if any(k in exc_lower for k in (
        "nocredentialserror",
        "partialcredentialserror",
        "unable to locate credentials",
        "credentials not found",
        "the security token included in the request is invalid",
    )) or exc_type in ("NoCredentialsError", "PartialCredentialsError"):
        return (
            "missing_credentials",
            "AWS credentials not found. Configure AWS_ACCESS_KEY_ID and AWS_SECRET_ACCESS_KEY in .env.",
            "BEDROCK UNAVAILABLE — MISSING CREDENTIALS",
        )

    # 2. Access Denied / Auth
    if any(k in exc_lower for k in (
        "accessdenied",
        "accessdeniedexception",
        "unauthorizedoperation",
        "not authorized to perform",
        "is not authorized",
    )) or "403" in exc_lower:
        return (
            "access_denied",
            f"Access denied to Bedrock model: {_sanitize_error_message(exc_msg)}. Check IAM permissions for bedrock:InvokeModel.",
            "BEDROCK UNAVAILABLE — ACCESS DENIED",
        )

    # 3. Throttling / Rate limit / Daily quota (Fail fast, no retries)
    if any(k in exc_lower for k in (
        "throttling",
        "throttlingexception",
        "toomanyrequestsexception",
        "rate exceeded",
        "token-per-day",
        "quota exceeded",
        "limit exceeded",
        "429",
    )) or exc_type in ("ThrottlingException", "TooManyRequestsException"):
        return (
            "throttling",
            f"Bedrock rate limit or daily quota exceeded: {_sanitize_error_message(exc_msg)}. Failing fast without retrying.",
            "BEDROCK UNAVAILABLE — THROTTLED",
        )

    # 4. Timeout / Network
    if any(k in exc_lower for k in (
        "timeout",
        "timeouterror",
        "connecttimeouterror",
        "readtimeouterror",
        "endpointconnectionerror",
        "connection refused",
    )) or exc_type in ("TimeoutError", "ConnectTimeoutError", "ReadTimeoutError", "EndpointConnectionError"):
        return (
            "timeout",
            f"Network timeout contacting Bedrock endpoint: {_sanitize_error_message(exc_msg)}.",
            "BEDROCK UNAVAILABLE — TIMEOUT",
        )

    # 5. Generic service error
    clean_msg = _sanitize_error_message(exc_msg)
    return (
        "service_error",
        f"{exc_type}: {clean_msg}",
        "BEDROCK UNAVAILABLE — SERVICE ERROR",
    )


def _mock_assessment(
    incident: dict[str, Any],
    action_taken: str,
    evidence: str,
) -> dict[str, Any]:
    """Build a deterministic assessment without external services."""
    title = incident.get("title", "Unspecified incident")
    service = incident.get("service", "unknown service")
    severity = incident.get("severity", "unknown")
    description = incident.get("description", "No description provided.")

    assessment = (
        "MOCK ASSESSMENT — NOT GENERATED BY BEDROCK\n\n"
        "SITUATION\n"
        f"{severity} incident affecting {service}: {title}. "
        f"Reported details: {description} "
        "This is a demo assessment, not a verified diagnosis.\n\n"
        "EVIDENCE\n"
        f"- Diagnostic action selected by Strands Decider: {action_taken}\n"
        "- Evidence below is simulated and has not been checked against "
        "live infrastructure.\n"
        f"{evidence}\n\n"
        "NEXT STEPS\n"
        "1. Validate these findings against live logs, metrics, and "
        "deployment records.\n"
        "2. Confirm the suspected cause before making production changes.\n"
        "3. Follow your incident-response and rollback procedures as "
        "appropriate."
    )

    return {
        "assessment": assessment,
        "model": None,
        "available": False,
        "provider": "mock",
        "status": "mock",
        "label": "MOCK — NOT GENERATED BY BEDROCK",
        "error_category": None,
    }


def _unavailable_response(
    reason: str,
    category: str = "service_error",
    label: str | None = None,
) -> dict[str, Any]:
    """Describe a failed Bedrock assessment without disguising it as a mock."""
    return {
        "assessment": (
            f"Bedrock assessment unavailable [{category}]: {reason}\n\n"
            "No live model assessment was generated. Switch to "
            "ASSESSMENT_PROVIDER=mock for a self-contained demo, or check "
            "the Bedrock configuration before retrying."
        ),
        "model": BEDROCK_MODEL_ID,
        "available": False,
        "provider": "bedrock",
        "status": "unavailable",
        "label": label or f"BEDROCK UNAVAILABLE — {category.upper()}",
        "error_category": category,
    }


def _bedrock_assessment(
    incident: dict[str, Any],
    action_taken: str,
    evidence: str,
) -> dict[str, Any]:
    """Call the existing Strands Agents SDK integration with Bedrock."""
    try:
        from strands import Agent
    except ImportError as exc:
        return _unavailable_response(
            reason=f"strands-agents is not installed: {exc}",
            category="import_error",
            label="BEDROCK UNAVAILABLE — SDK MISSING",
        )

    user_msg = (
        f"INCIDENT DETAILS\n"
        f"ID: {incident.get('id', 'N/A')}\n"
        f"Severity: {incident.get('severity', 'unknown')}\n"
        f"Service: {incident.get('service', 'unknown')}\n"
        f"Title: {incident.get('title', '')}\n"
        f"Description: {incident.get('description', '')}\n\n"
        f"DIAGNOSTIC ACTION: {action_taken}\n\n"
        f"SIMULATED EVIDENCE\n{evidence}\n\n"
        "Produce the incident assessment."
    )

    try:
        agent = Agent(
            model=BEDROCK_MODEL_ID,
            system_prompt=ASSESSMENT_PROMPT,
        )
        result = agent(user_msg)
        return {
            "assessment": str(result),
            "model": BEDROCK_MODEL_ID,
            "available": True,
            "provider": "bedrock",
            "status": "live",
            "label": f"BEDROCK — {BEDROCK_MODEL_ID}",
            "error_category": None,
        }
    except Exception as exc:
        category, message, label = classify_bedrock_error(exc)
        return _unavailable_response(reason=message, category=category, label=label)


def assess_incident(
    incident: dict[str, Any],
    action_taken: str,
    evidence: str,
) -> dict[str, Any]:
    """Assess an incident using the explicitly configured provider.

    ASSESSMENT_PROVIDER defaults to ``mock``. Set it to ``bedrock`` to opt
    into the live Strands Agents / Amazon Bedrock integration.
    """
    provider = os.environ.get("ASSESSMENT_PROVIDER", "mock").strip().lower()

    if provider == "mock":
        return _mock_assessment(incident, action_taken, evidence)

    if provider == "bedrock":
        return _bedrock_assessment(incident, action_taken, evidence)

    return {
        **_unavailable_response(
            f"unknown ASSESSMENT_PROVIDER value: {provider!r}",
            category="configuration_error",
            label="ASSESSMENT CONFIGURATION ERROR",
        ),
        "status": "configuration_error",
        "label": "ASSESSMENT CONFIGURATION ERROR",
        "error_category": "configuration_error",
    }

